export function fileIcon(name: string): string {
  if (/\.(png|jpe?g|gif|svg|webp|eps)$/i.test(name)) return icon("image", 15);
  if (/\.bib$/i.test(name)) return icon("book", 15);
  if (/\.(tex|sty|cls|ltx)$/i.test(name)) return icon("fileText", 15);
  return icon("file", 15);
}
